export enum ErrorCode {
  // Common / System
  INTERNAL_ERROR = 'INTERNAL_ERROR',
  VALIDATION_ERROR = 'VALIDATION_ERROR',
  UNAUTHORIZED = 'UNAUTHORIZED',
  FORBIDDEN = 'FORBIDDEN',
  RESOURCE_NOT_FOUND = 'RESOURCE_NOT_FOUND',
  CONFLICT = 'CONFLICT',
  BAD_REQUEST = 'BAD_REQUEST',

  // Users & Auth
  USER_NOT_FOUND = 'USER_NOT_FOUND',
  EMAIL_ALREADY_EXISTS = 'EMAIL_ALREADY_EXISTS',
  INVALID_CREDENTIALS = 'INVALID_CREDENTIALS',
  ACCOUNT_SUSPENDED = 'ACCOUNT_SUSPENDED',
  INVALID_OR_EXPIRED_OTP = 'INVALID_OR_EXPIRED_OTP',
  EMAIL_NOT_VERIFIED = 'EMAIL_NOT_VERIFIED',

  // Tickets & Sessions
  TICKET_NOT_FOUND = 'TICKET_NOT_FOUND',
  TICKET_NOT_PENDING = 'TICKET_NOT_PENDING',
  TICKET_ALREADY_CLAIMED = 'TICKET_ALREADY_CLAIMED',
  SESSION_NOT_FOUND = 'SESSION_NOT_FOUND',
  SESSION_NOT_COMPLETED = 'SESSION_NOT_COMPLETED',
  SESSION_ALREADY_ACTIVE = 'SESSION_ALREADY_ACTIVE',
  UNAUTHORIZED_SESSION_PARTICIPANT = 'UNAUTHORIZED_SESSION_PARTICIPANT',

  // Reviews
  REVIEW_ALREADY_SUBMITTED = 'REVIEW_ALREADY_SUBMITTED',
  ONLY_STUDENT_CAN_REVIEW = 'ONLY_STUDENT_CAN_REVIEW',

  // Settings
  SETTINGS_NOT_FOUND = 'SETTINGS_NOT_FOUND',
}

export class AppException extends Error {
  constructor(
    public readonly code: ErrorCode,
    message: string,
    public readonly details?: unknown,
  ) {
    super(message);
    this.name = 'AppException';
  }
}
